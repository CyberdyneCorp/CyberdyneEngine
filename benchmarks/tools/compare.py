#!/usr/bin/env python3
"""Compare a benchmark run against the committed baseline, and fail when a threshold is crossed.

Task 4.1.5. The runner measures; this decides. `testing-and-quality` requires that benchmarks "fail
when a metric regresses beyond a per-benchmark threshold", and that an intentional trade-off updates
the threshold in the same change with a recorded justification — so the baseline is a reviewed file,
and re-recording it is a deliberate step (`just test-bench --record`) rather than something a
failing run does for itself.

The comparison is on the ratio each result carries — its cost divided by the cost of a calibration
workload measured in the same process — not on nanoseconds. A nanosecond baseline is a property of
the machine that recorded it; a ratio survives being run on a different one, which is what makes the
threshold worth keeping. See the note at the top of benchmarks/harness/src/bench.cpp.

Exit status: 0 when every benchmark is within its threshold, 1 when one is not or has none, 2 on a
usage error.
"""

from __future__ import annotations

import argparse
import datetime
import json
import sys
from pathlib import Path

# The tolerance a newly recorded benchmark gets. Wide enough that a different compiler or a
# different core does not fail the build, narrow enough that a doubling cannot hide in it. A
# benchmark that needs another value carries it in its own baseline entry.
DEFAULT_TOLERANCE = 0.20


def load_json(path: Path, what: str) -> dict:
    if not path.is_file():
        raise SystemExit(f"compare.py: no {what} at {path}")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise SystemExit(f"compare.py: {path} is not valid JSON: {error}") from error


def baseline_entries(baseline: dict) -> dict:
    return baseline.get("benchmarks", {})


def compare_one(result: dict, entry: dict | None) -> tuple[str, str]:
    """Return (status, explanation) for one benchmark. Status is ok, regressed, faster or missing."""
    name = result["name"]
    ratio = result["ratio"]

    if entry is None:
        return "missing", (
            f"{name} has no entry in the baseline, so it has no threshold. A number with no budget "
            f"is a measurement, not a gate — record it with `just test-bench --record` in the "
            f"change that adds the benchmark."
        )

    recorded = entry["ratio"]
    tolerance = entry.get("tolerance", DEFAULT_TOLERANCE)
    limit = recorded * (1.0 + tolerance)
    change = (ratio / recorded - 1.0) * 100.0 if recorded else 0.0

    if ratio > limit:
        return "regressed", (
            f"{name}: {ratio:.4f} against a baseline of {recorded:.4f} "
            f"(+{change:.1f}%, tolerance {tolerance * 100:.0f}%)."
        )
    if ratio < recorded * (1.0 - tolerance):
        return "faster", (
            f"{name}: {ratio:.4f} against a baseline of {recorded:.4f} ({change:.1f}%). "
            f"Faster than the threshold allows for — re-record so the gate defends the new number."
        )
    return "ok", f"{name}: {ratio:.4f} against a baseline of {recorded:.4f} ({change:+.1f}%)."


def record(results: dict, baseline: dict, path: Path) -> None:
    """Write the baseline from a run, keeping each benchmark's reviewed tolerance."""
    previous = baseline_entries(baseline)
    entries = {}
    for result in results["benchmarks"]:
        name = result["name"]
        entries[name] = {
            "ratio": round(result["ratio"], 4),
            "tolerance": previous.get(name, {}).get("tolerance", DEFAULT_TOLERANCE),
            "ns_per_op_when_recorded": round(result["ns_per_op"], 4),
            "recorded_on": datetime.date.today().isoformat(),
        }

    baseline["note"] = (
        "Thresholds for benchmarks/. `ratio` is the benchmark's cost divided by the calibration "
        "workload measured in the same run, so it compares across machines; `tolerance` is the "
        "fraction it may rise by before the run fails. Regenerated by `just test-bench --record`, "
        "and a change to it is a reviewed change: it is the record of an intentional trade-off."
    )
    baseline["calibration_ns_per_op_when_recorded"] = round(
        results["calibration"]["ns_per_op"], 4
    )
    baseline["benchmarks"] = dict(sorted(entries.items()))
    path.write_text(json.dumps(baseline, indent=2) + "\n", encoding="utf-8")
    print(f"recorded {len(entries)} threshold(s) in {path}")


def report(results: dict, baseline: dict) -> int:
    entries = baseline_entries(baseline)
    failures: list[str] = []

    for result in results["benchmarks"]:
        status, explanation = compare_one(result, entries.get(result["name"]))
        label = {"ok": "ok  ", "regressed": "FAIL", "faster": "note", "missing": "FAIL"}[status]
        print(f"{label} {explanation}")
        if status in ("regressed", "missing"):
            failures.append(explanation)

    measured = {result["name"] for result in results["benchmarks"]}
    for stale in sorted(set(entries) - measured):
        print(f"note {stale} is in the baseline but was not measured — re-record to prune it.")

    if failures:
        print(f"\n{len(failures)} benchmark(s) outside their threshold.")
        return 1
    print(f"\n{len(measured)} benchmark(s) within their thresholds.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", required=True, type=Path, help="the runner's JSON output")
    parser.add_argument("--baseline", required=True, type=Path, help="the committed thresholds")
    parser.add_argument("--record", action="store_true",
                        help="rewrite the baseline from this run (a reviewed step)")
    arguments = parser.parse_args()

    results = load_json(arguments.results, "results file")
    if not results.get("benchmarks"):
        raise SystemExit(f"compare.py: {arguments.results} contains no benchmark results")

    baseline = {}
    if arguments.baseline.is_file():
        baseline = load_json(arguments.baseline, "baseline")
    elif not arguments.record:
        raise SystemExit(
            f"compare.py: no baseline at {arguments.baseline}. Record one with "
            f"`just test-bench --record`, and review it in the change that adds it."
        )

    if arguments.record:
        record(results, baseline, arguments.baseline)
        return 0
    return report(results, baseline)


if __name__ == "__main__":
    sys.exit(main())
