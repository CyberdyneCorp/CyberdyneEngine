#!/usr/bin/env python3
"""Generate THIRD_PARTY.md from deps/manifest.toml.

`thirdparty-dependencies` requires a complete attribution document generated from the manifest.
Generated, not written: an attribution list maintained by hand is one a dependency bump forgets, and
the licences it omits are the ones nobody notices until shipping.

    tools/deps/attribution.py            regenerate THIRD_PARTY.md
    tools/deps/attribution.py --check    exit non-zero if it is stale

The output depends only on the manifest — no timestamps, no paths, no environment — so `--check` in
CI answers exactly one question: has somebody changed the manifest without regenerating the
document?
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from manifest import REPO_ROOT, Dependency, ManifestError, load

OUTPUT = REPO_ROOT / "THIRD_PARTY.md"

HEADER = """\
# Third-party software

CyberdyneEngine integrates the software listed here. Each dependency sits behind an engine-owned
interface, is pinned to an exact commit, and carries a permissive licence — the conditions
`thirdparty-dependencies` sets for adopting one at all.

<!-- Generated by tools/deps/attribution.py from deps/manifest.toml. Do not edit: run
     `just maintenance-deps` instead. CI fails when this file and the manifest disagree. -->

## What a build actually links

A dependency with a gating option is fetched, built and linked **only** when that option is on. A
build with the option off contains none of its code, so the notices it requires do not apply to
that build. The engine's runtime attribution reports the set for the build in hand rather than this
whole table.

| Dependency | Version | Licence | Included when | Links into |
|---|---|---|---|---|
"""

SCOPE_TEXT = {
    "runtime": "a shipped game",
    "tool-time": "the editor and the cooker only",
    "test": "the test binaries only",
    "development": "development builds only",
}


def _summary_row(dependency: Dependency) -> str:
    gate = f"`{dependency.gate}` is on" if dependency.gate else "always"
    return (
        f"| [{dependency.name}]({dependency.repository}) | {dependency.version} "
        f"| {dependency.licence} | {gate} | {SCOPE_TEXT[dependency.scope]} |"
    )


def _entry(dependency: Dependency) -> str:
    gate = f"`{dependency.gate}` is on" if dependency.gate else "always"
    return f"""\
### {dependency.name} {dependency.version}

- **Upstream**: {dependency.repository}
- **Pinned at**: `{dependency.commit}` (`{dependency.tag}`)
- **Licence**: {dependency.licence}
- **Licence text**: [`{dependency.licence_file}`]({dependency.licence_url}), and
  `{dependency.licence_file}` at the root of the fetched source in any configured build tree
- **Behind**: {dependency.interface}
- **Included when**: {gate}
- **Linked into**: {SCOPE_TEXT[dependency.scope]}
- **Why integrated rather than built**: {dependency.justification}
"""


def render(dependencies: list[Dependency]) -> str:
    parts = [HEADER]
    parts.extend(f"{_summary_row(d)}\n" for d in dependencies)
    parts.append("\n## Notices\n\n")
    parts.append("\n".join(_entry(d) for d in dependencies))
    return "".join(parts)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero if THIRD_PARTY.md is not what the manifest generates",
    )
    arguments = parser.parse_args(argv)

    try:
        dependencies = load()
    except ManifestError as error:
        print(f"deps/manifest.toml: {error}", file=sys.stderr)
        return 2

    generated = render(dependencies)
    relative = OUTPUT.relative_to(REPO_ROOT)

    if not arguments.check:
        OUTPUT.write_text(generated, encoding="utf-8")
        print(f"wrote {relative} — {len(dependencies)} dependencies")
        return 0

    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
    if current == generated:
        print(f"{relative} is current")
        return 0
    print(
        f"{relative} does not match deps/manifest.toml.\n"
        f"  Regenerate it:  just maintenance-deps",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
