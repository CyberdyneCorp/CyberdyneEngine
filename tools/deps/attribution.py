#!/usr/bin/env python3
"""Generate THIRD_PARTY.md from deps/manifest.toml and deps/host-tools.toml.

`thirdparty-dependencies` requires a complete attribution document generated from the manifest.
Generated, not written: an attribution list maintained by hand is one a dependency bump forgets, and
the licences it omits are the ones nobody notices until shipping.

    tools/deps/attribution.py            regenerate THIRD_PARTY.md
    tools/deps/attribution.py --check    exit non-zero if it is stale

The output depends only on the two manifests — no timestamps, no paths, no environment — so
`--check` in CI answers exactly one question: has somebody changed a manifest without regenerating
the document?

It also checks that each host prerequisite's declared version still appears in the file that loads
it. Those pins lived in tools/gen/reflect/parse.py and in .github/workflows/ci.yml and in no table
anybody audited, which is how they stayed undeclared through a whole milestone.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from manifest import (
    REPO_ROOT,
    Dependency,
    HostTool,
    ManifestError,
    check_host_tool_pins,
    load,
    load_host_tools,
)

OUTPUT = REPO_ROOT / "THIRD_PARTY.md"

HEADER = """\
# Third-party software

CyberdyneEngine integrates the software listed here. Each dependency sits behind an engine-owned
interface, is pinned to an exact commit, and carries a permissive licence — the conditions
`thirdparty-dependencies` sets for adopting one at all.

The second table is a different kind of entry and says so where it starts: software a contributor's
machine must provide for one tool-time step, which the engine never fetches, links or redistributes.

<!-- Generated by tools/deps/attribution.py from deps/manifest.toml and deps/host-tools.toml. Do not
     edit: run `just maintenance-deps` instead. CI fails when this file and the manifests
     disagree. -->

## What a build actually links

A dependency with a gating option is fetched, built and linked **only** when that option is on. A
build with the option off contains none of its code, so the notices it requires do not apply to
that build. The engine's runtime attribution reports the set for the build in hand rather than this
whole table.

| Dependency | Version | Licence | Included when | Links into |
|---|---|---|---|---|
"""

SCOPE_TEXT = {
    "runtime": "a shipped game",
    "tool-time": "the editor and the cooker only",
    "test": "the test binaries only",
    "development": "development builds only",
}


def _summary_row(dependency: Dependency) -> str:
    gate = f"`{dependency.gate}` is on" if dependency.gate else "always"
    return (
        f"| [{dependency.name}]({dependency.repository}) | {dependency.version} "
        f"| {dependency.licence} | {gate} | {SCOPE_TEXT[dependency.scope]} |"
    )


def _entry(dependency: Dependency) -> str:
    gate = f"`{dependency.gate}` is on" if dependency.gate else "always"
    return f"""\
### {dependency.name} {dependency.version}

- **Upstream**: {dependency.repository}
- **Pinned at**: `{dependency.commit}` (`{dependency.tag}`)
- **Licence**: {dependency.licence}
- **Licence text**: [`{dependency.licence_file}`]({dependency.licence_url}), and
  `{dependency.licence_file}` at the root of the fetched source in any configured build tree
- **Behind**: {dependency.interface}
- **Included when**: {gate}
- **Linked into**: {SCOPE_TEXT[dependency.scope]}
- **Why integrated rather than built**: {dependency.justification}
"""


HOST_TOOLS_HEADER = """
## Host prerequisites, which are not linked and not shipped

These are **not** part of any artefact the engine produces. They are software that has to be present
on a contributor's machine for one tool-time step — parsing annotated C++ to regenerate reflection
metadata — and the engine neither fetches, links, nor redistributes them. They are listed because
`thirdparty-dependencies` asks for a complete record of third-party software the project depends on,
and because a prerequisite nobody declared is one a fresh clone discovers by failing.

The generated metadata is committed, so a clone builds and tests without any of these; only
regeneration needs them, and `just generate-check` is what notices.

| Prerequisite | Version | Licence | Kind | Needed for | Install |
|---|---|---|---|---|---|
"""


def _host_row(tool: HostTool) -> str:
    return (
        f"| [{tool.package}]({tool.upstream}) | {tool.version} | {tool.licence} | {tool.kind} "
        f"| `{tool.checked_by}` | `{tool.install_linux}` |"
    )


def _host_entry(tool: HostTool) -> str:
    return f"""\
### {tool.package} {tool.version}

- **Upstream**: {tool.upstream}
- **Licence**: {tool.licence} ([`{tool.licence_file}`]({tool.upstream}))
- **Kind**: {tool.kind}, provided by the host — never fetched, never linked, never redistributed
- **Loaded by**: `{tool.consumer}`
- **Absence is caught by**: `{tool.checked_by}`, and reported by `just env-doctor`
- **Install**: `{tool.install_linux}` (Linux), `{tool.install_macos}` (macOS),
  `{tool.install_windows}` (Windows)
- **Why a host prerequisite rather than a fetched dependency**: {tool.justification}
"""


def render(dependencies: list[Dependency], host_tools: list[HostTool]) -> str:
    parts = [HEADER]
    parts.extend(f"{_summary_row(d)}\n" for d in dependencies)
    parts.append(HOST_TOOLS_HEADER)
    parts.extend(f"{_host_row(t)}\n" for t in host_tools)
    parts.append("\n## Notices\n\n")
    parts.append("\n".join(_entry(d) for d in dependencies))
    parts.append("\n")
    parts.append("\n".join(_host_entry(t) for t in host_tools))
    return "".join(parts)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero if THIRD_PARTY.md is not what the manifest generates",
    )
    arguments = parser.parse_args(argv)

    try:
        dependencies = load()
    except ManifestError as error:
        print(f"deps/manifest.toml: {error}", file=sys.stderr)
        return 2
    try:
        host_tools = load_host_tools()
    except ManifestError as error:
        print(f"deps/host-tools.toml: {error}", file=sys.stderr)
        return 2

    # A declaration that has drifted from the code loading it is worse than no declaration: it reads
    # as an audited fact. Checked before the document is written, so a stale pin cannot be published.
    complaints = check_host_tool_pins(host_tools)
    if complaints:
        for complaint in complaints:
            print(f"deps/host-tools.toml: {complaint}", file=sys.stderr)
        return 2

    generated = render(dependencies, host_tools)
    relative = OUTPUT.relative_to(REPO_ROOT)

    if not arguments.check:
        OUTPUT.write_text(generated, encoding="utf-8")
        print(
            f"wrote {relative} — {len(dependencies)} dependencies, "
            f"{len(host_tools)} host prerequisites"
        )
        return 0

    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
    if current == generated:
        print(f"{relative} is current")
        return 0
    print(
        f"{relative} does not match deps/manifest.toml and deps/host-tools.toml.\n"
        f"  Regenerate it:  just maintenance-deps",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
