#!/usr/bin/env python3
"""Generate cy_features.h and cy_modules.h from the resolved build configuration.

Task 1.4.3. `build-system-and-platforms` requires generation to be deterministic: identical inputs
produce byte-identical outputs, so generated artefacts do not churn in builds or defeat caches.
That is why this is a separate program rather than a `configure_file()` in CMake — a program can be
run twice and diffed, and `--check` is the same code path as the write, so a currency check cannot
disagree with the generator it checks.

The input is written by cmake/features.cmake at configure time. It is line oriented, sorted, and
space separated because no field may contain a space:

    version 1
    feature <NAME> <ON|OFF>
    setting <NAME> <value>
    module <name> <IDENT> <ON|OFF> <level> <level-index> <layer> <layer-index> <hot-reload>

Usage:
    generate_headers.py --input <inputs.txt> --output-dir <dir>
    generate_headers.py --input <inputs.txt> --output-dir <dir> --check
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

INPUT_VERSION = "1"

BANNER = """\
// Generated by tools/gen/generate_headers.py. Do not edit.
//
// Regenerate with `just generate-headers`; `just generate-check` fails when this file is stale.
// The content is decided by cmake/features.cmake and the module manifests it discovered, so a
// change belongs there and not here.
"""


@dataclass(frozen=True)
class Feature:
    name: str
    enabled: bool


@dataclass(frozen=True)
class Setting:
    name: str
    value: str


@dataclass(frozen=True)
class Module:
    name: str
    identifier: str
    enabled: bool
    level: str
    level_index: int
    layer: str
    layer_index: int
    hot_reload: bool


@dataclass(frozen=True)
class Inputs:
    features: tuple[Feature, ...]
    settings: tuple[Setting, ...]
    modules: tuple[Module, ...]


class InputError(Exception):
    """A malformed input file. Reported with the offending line, never ignored."""


def _boolean(token: str, where: str) -> bool:
    if token in ("ON", "1", "TRUE", "YES"):
        return True
    if token in ("OFF", "0", "FALSE", "NO"):
        return False
    raise InputError(f"{where}: expected ON or OFF, found '{token}'")


def _parse_record(fields: list[str], where: str, buckets: dict[str, list]) -> None:
    kind = fields[0]
    if kind == "feature":
        _expect(fields, 3, where)
        buckets["features"].append(Feature(fields[1], _boolean(fields[2], where)))
    elif kind == "setting":
        # A setting carries a value rather than a state: CY_SANITIZE is 'address,undefined', not
        # ON. The value may be empty, which is how an unset setting reaches the header.
        _expect(fields, 2, where, exact=False)
        buckets["settings"].append(Setting(fields[1], " ".join(fields[2:])))
    elif kind == "module":
        _expect(fields, 9, where)
        buckets["modules"].append(
            Module(
                name=fields[1],
                identifier=fields[2],
                enabled=_boolean(fields[3], where),
                level=fields[4],
                level_index=int(fields[5]),
                layer=fields[6],
                layer_index=int(fields[7]),
                hot_reload=_boolean(fields[8], where),
            )
        )
    elif kind == "version":
        _expect(fields, 2, where)
        if fields[1] != INPUT_VERSION:
            raise InputError(
                f"{where}: input format version {fields[1]}, but this generator speaks "
                f"{INPUT_VERSION}. cmake/features.cmake and tools/gen/generate_headers.py are out "
                f"of step."
            )
    else:
        raise InputError(f"{where}: unknown record '{kind}'")


def _expect(fields: list[str], count: int, where: str, exact: bool = True) -> None:
    if (exact and len(fields) != count) or (not exact and len(fields) < count):
        raise InputError(f"{where}: expected {count} fields, found {len(fields)}")


def read_inputs(path: Path) -> Inputs:
    buckets: dict[str, list] = {"features": [], "settings": [], "modules": []}
    seen_version = False
    for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        fields = line.split()
        _parse_record(fields, f"{path}:{number}", buckets)
        seen_version = seen_version or fields[0] == "version"
    if not seen_version:
        raise InputError(f"{path}: no 'version' record; the file is not a generator input")
    # Sorting here rather than trusting the writer is what makes the output reproducible from an
    # input whose order changed for an unrelated reason.
    return Inputs(
        features=tuple(sorted(buckets["features"], key=lambda f: f.name)),
        settings=tuple(sorted(buckets["settings"], key=lambda s: s.name)),
        modules=tuple(sorted(buckets["modules"], key=lambda m: (m.level_index, m.name))),
    )


def _guard(body: str, macro: str) -> str:
    return f"{BANNER}\n#ifndef {macro}\n#define {macro}\n\n{body}\n#endif  // {macro}\n"


def _x_macro(name: str, rows: list[str]) -> str:
    if not rows:
        # An empty X-macro must still expand to nothing rather than to a syntax error.
        return f"#define {name}(X)\n"
    joined = " \\\n".join(f"    {row}" for row in rows)
    return f"#define {name}(X) \\\n{joined}\n"


def render_features(inputs: Inputs) -> str:
    lines: list[str] = [
        "// Feature options, from cmake/features.cmake.",
        "//",
        "// An enabled feature is defined to 1. A disabled feature is not defined at all, so",
        "// `#if defined(CY_UI)` and `#ifdef CY_UI` both answer correctly. Disabling a feature",
        "// excludes its sources and its dependencies from the build; this header records the",
        "// decision, it does not implement a runtime stub.",
        "",
    ]
    for feature in inputs.features:
        if feature.enabled:
            lines.append(f"#define {feature.name} 1")
        else:
            lines.append(f"/* {feature.name} is disabled */")

    if inputs.settings:
        lines += ["", "// Settings carry a value rather than a state."]
        for setting in inputs.settings:
            if setting.value:
                lines.append(f'#define {setting.name} "{setting.value}"')
            else:
                lines.append(f"/* {setting.name} is unset */")

    lines += [
        "",
        "// Every feature, enabled or not, for code that reports the build configuration.",
        "// X(name, enabled): the name is a string, never the macro, which would expand to 1.",
        "",
    ]
    rows = [f'X("{f.name}", {int(f.enabled)})' for f in inputs.features]
    lines.append(_x_macro("CY_FEATURE_TABLE", rows))
    lines.append(f"#define CY_FEATURE_COUNT {len(inputs.features)}")
    lines.append("")
    return _guard("\n".join(lines), "CY_FEATURES_H")


def render_modules(inputs: Inputs) -> str:
    enabled = [m for m in inputs.modules if m.enabled]
    disabled = [m for m in inputs.modules if not m.enabled]
    lines: list[str] = [
        "// Modules discovered from their manifests, from cmake/modules.cmake.",
        "//",
        "// CY_MODULE_<NAME> is defined to 1 for an enabled module and is not defined at all for a",
        "// disabled one, whose sources are excluded from the build entirely.",
        "//",
        "// The table below is in initialisation order: registration level, then name. Registration",
        "// level orders initialisation; layer constrains dependencies. The two are distinct and a",
        "// module carries both.",
        "",
    ]
    for module in enabled:
        lines.append(f"#define CY_MODULE_{module.identifier.upper()} 1")
    for module in disabled:
        lines.append(f"/* CY_MODULE_{module.identifier.upper()} is disabled */")

    lines += [
        "",
        "// X(name, identifier, level, level_index, layer, layer_index, hot_reload)",
        "",
    ]
    rows = [
        'X("{name}", {ident}, "{level}", {level_index}, "{layer}", {layer_index}, {hot})'.format(
            name=m.name,
            ident=m.identifier,
            level=m.level,
            level_index=m.level_index,
            layer=m.layer,
            layer_index=m.layer_index,
            hot=int(m.hot_reload),
        )
        for m in enabled
    ]
    lines.append(_x_macro("CY_MODULE_TABLE", rows))
    lines.append(f"#define CY_MODULE_COUNT {len(enabled)}")
    lines.append("")
    return _guard("\n".join(lines), "CY_MODULES_H")


def rendered(inputs: Inputs) -> dict[str, str]:
    return {"cy_features.h": render_features(inputs), "cy_modules.h": render_modules(inputs)}


def write(output_dir: Path, files: dict[str, str]) -> list[str]:
    """Write each file, touching only the ones whose content changed.

    Rewriting an unchanged header would make every configure invalidate every compilation that
    includes it, which is the churn the determinism requirement exists to prevent.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, content in sorted(files.items()):
        path = output_dir / name
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        path.write_text(content, encoding="utf-8")
        changed.append(name)
    return changed


def check(output_dir: Path, files: dict[str, str]) -> list[str]:
    stale = []
    for name, content in sorted(files.items()):
        path = output_dir / name
        if not path.exists():
            stale.append(f"{path}: missing")
        elif path.read_text(encoding="utf-8") != content:
            stale.append(f"{path}: differs from what the generator produces")
    return stale


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--input", required=True, type=Path, help="the generator input file")
    parser.add_argument("--output-dir", required=True, type=Path, help="where the headers go")
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero naming every file that is not current",
    )
    args = parser.parse_args(argv)

    if not args.input.is_file():
        print(f"generate_headers: no input at {args.input}", file=sys.stderr)
        print("  Configure the build first: `just build-engine` or `cmake --preset dev`.", file=sys.stderr)
        return 2

    try:
        files = rendered(read_inputs(args.input))
    except InputError as error:
        print(f"generate_headers: {error}", file=sys.stderr)
        return 2

    if args.check:
        stale = check(args.output_dir, files)
        for line in stale:
            print(f"generate_headers: {line}", file=sys.stderr)
        if stale:
            print("  Regenerate with `just generate-headers`.", file=sys.stderr)
            return 1
        print(f"generated headers are current in {args.output_dir}")
        return 0

    changed = write(args.output_dir, files)
    print(f"generated headers in {args.output_dir}" + (f" (updated: {', '.join(changed)})" if changed else " (unchanged)"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
