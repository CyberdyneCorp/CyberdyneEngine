"""The generated C++. Task 1.1.2.

One header and one translation unit per annotated header, plus one aggregate that registers them
all. `core-type-system` requires the generated output stay engine-owned, and it is: these are the
engine's own descriptor types, filled in with the engine's own identifiers.

Three properties the emitter is written to hold.

**Nothing measured by the parser is written as a number.** Sizes, alignments and offsets are emitted
as `sizeof`, `alignof` and `offsetof` so the *compiler* computes them for the target being built.
A generator that baked in the sizes it saw would produce output that is wrong on any target whose
ABI differs from the host's, and would do it silently.

**Layout claims are asserted where they can fail.** The generated translation unit static_asserts
that a reflected type is standard-layout and not polymorphic, so annotating a type that has a vtable
is a compile error naming it rather than a descriptor whose offsets mean nothing.

**Output is byte-reproducible.** Paths are source-root relative, entries are emitted in a fixed
order, and there is no timestamp, no host name and no build directory anywhere in it.
"""

from __future__ import annotations

from dataclasses import dataclass

from .attrspec import PARAMETER_TYPES as _PARAMETER_CPP
from .attrspec import Attributes, CustomValue
from .model import ParsedHeader, ParsedType

GENERATOR_VERSION = "1"

BANNER = """\
// clang-format off
// NOLINTBEGIN
// Generated by tools/gen/reflect_gen.py. Do not edit.
//
// Source: {source}
// Regenerate with `just generate-headers`; `just generate-check` fails when this file is stale, and
// `just quality-identity` fails when an identifier in it has moved.
//
// Every identifier below is read from identity/manifest.toml. Nothing here is derived from a name,
// so renaming a type or a field changes the manifest's `name` and this file's strings, and no
// number moves.
//
// clang-format is off for the whole file. Generated output must be byte-identical between runs, and
// running it through a formatter would make that a property of whichever formatter version happened
// to be on the contributor's PATH — `just quality-format-check` and `just generate-check` would then
// disagree about the same file. The emitter owns the layout instead. The marker is the first line
// of the file rather than a later one, because a formatter still reflows everything above it.
//
// clang-tidy is off for the same reason: a finding here is actionable only by editing
// tools/gen/reflect/emit.py, which is where the lint that matters belongs. The compiler's warning
// set still applies, with -Werror, exactly as it does to every other translation unit.
"""

# Closes the NOLINTBEGIN the banner opens. Every generated file ends with it.
TRAILER = "// NOLINTEND"


def _document(lines: list[str]) -> str:
    return "\n".join([*lines, "", TRAILER]) + "\n"


@dataclass
class Output:
    path: str  # relative to the output directory
    text: str


def slug_of(include_path: str) -> str:
    """The C++ identifier fragment for one header: cy/core/x/y.h -> cy_core_x_y."""
    stem = include_path[:-2] if include_path.endswith(".h") else include_path
    return "".join(character if character.isalnum() else "_" for character in stem)


def outputs_for(include_path: str) -> tuple[str, str]:
    """The generated header and translation unit for one annotated header."""
    stem = include_path[:-2] if include_path.endswith(".h") else include_path
    return f"{stem}.reflect.h", f"{stem}.reflect.cpp"


def render_header(parsed: ParsedHeader, identity, schemas_used) -> Output:
    slug = slug_of(parsed.include_path)
    guard = f"CY_GENERATED_{slug.upper()}_REFLECT_H"
    lines = [
        BANNER.format(source=parsed.path),
        "",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <cy/core/base/types.h>",
        "#include <cy/core/reflect/registry.h>",
        f"#include <{parsed.include_path}>",
        "",
    ]
    lines += _custom_attribute_structs(schemas_used)
    lines += ["namespace cy::reflect {", ""]
    for parsed_type in parsed.types:
        identifier = identity.types[parsed_type.name]
        lines += [
            f"/// Metadata for {parsed_type.name}, TypeId {identifier}.",
            "template <>",
            f"struct Reflected<{parsed_type.qualified}> {{",
            f"    static constexpr TypeId id{{{identifier}}};",
            "    static const TypeInfo& info() noexcept;",
            "};",
            "",
        ]
    lines += [
        f"/// Register every type declared in {parsed.path}. Idempotent.",
        f"Status register_{slug}(TypeRegistry& registry);",
        "",
        "}  // namespace cy::reflect",
        "",
        f"#endif  // {guard}",
    ]
    return Output(outputs_for(parsed.include_path)[0], _document(lines))


def _custom_attribute_structs(schemas_used) -> list[str]:
    if not schemas_used:
        return []
    lines = [
        "// Attribute types this module declared for itself, emitted as typed structures — read",
        "// them with cy::reflect::find_custom<T>(field.attributes, \"<name>\").",
        "",
    ]
    for schema in sorted(schemas_used, key=lambda s: (s.namespace, s.struct)):
        opened = bool(schema.namespace)
        if opened:
            lines.append(f"namespace {schema.namespace} {{")
        if schema.doc:
            lines.append(f"/// {schema.doc}")
        lines.append(f"struct {schema.struct} {{")
        for parameter in schema.parameters:
            lines.append(f"    {_PARAMETER_CPP[parameter.type]} {parameter.name};")
        lines.append("};")
        if opened:
            lines.append(f"}}  // namespace {schema.namespace}")
        lines.append("")
    return lines


def render_source(parsed: ParsedHeader, identity) -> Output:
    slug = slug_of(parsed.include_path)
    generated_header = outputs_for(parsed.include_path)[0]
    lines = [
        BANNER.format(source=parsed.path),
        "",
        f"#include <{generated_header}>",
        "",
        "#include <cstddef>",
        "#include <new>",
        "#include <type_traits>",
        "",
        "namespace cy::reflect {",
        "namespace {",
        "",
    ]
    for index, parsed_type in enumerate(parsed.types):
        lines += _render_type(index, parsed_type, identity)
    lines += ["}  // namespace", ""]
    for index, parsed_type in enumerate(parsed.types):
        lines += [
            f"const TypeInfo& Reflected<{parsed_type.qualified}>::info() noexcept {{",
            f"    return type_{index}_;",
            "}",
            "",
        ]
    lines += [f"Status register_{slug}(TypeRegistry& registry) {{"]
    for index in range(len(parsed.types)):
        lines += [
            f"    if (auto added = registry.add(type_{index}_); !added) {{",
            "        return added;",
            "    }",
        ]
    lines += ["    return ok();", "}", "", "}  // namespace cy::reflect"]
    return Output(outputs_for(parsed.include_path)[1], _document(lines))


def _render_type(index: int, parsed: ParsedType, identity) -> list[str]:
    alias = f"Type{index}"
    lines = [
        f"// {parsed.name} — TypeId {identity.types[parsed.name]}, declared at "
        f"{parsed.header}:{parsed.line}.",
        f"using {alias} = {parsed.qualified};",
        "",
        f'static_assert(std::is_standard_layout_v<{alias}>,',
        f'              "{parsed.name} is annotated for reflection but is not standard-layout. '
        f'Reflection "',
        '              "is opt-in and data-oriented: a reflected type has no base class, no virtual "',
        '              "functions and no hidden fields, so that its offsets mean what they say.");',
        f'static_assert(!std::is_polymorphic_v<{alias}>,',
        f'              "{parsed.name} is annotated for reflection and has a vtable.");',
        "",
        f"void construct_{index}_(void* storage) {{",
        f"    ::new (storage) {alias}();",
        "}",
        f"void destruct_{index}_(void* object) {{",
        f"    static_cast<{alias}*>(object)->~{alias}();",
        "}",
        f"void copy_assign_{index}_(void* destination, const void* source) {{",
        f"    *static_cast<{alias}*>(destination) = *static_cast<const {alias}*>(source);",
        "}",
        "",
    ]

    numbers = identity.fields[parsed.name]
    for position, parsed_field in enumerate(parsed.fields):
        lines += _render_field_payloads(index, position, parsed_field.attributes)

    lines += [f"constexpr FieldInfo fields_{index}_[] = {{"]
    for position, parsed_field in enumerate(parsed.fields):
        lines += _render_field(index, position, alias, parsed_field, numbers[parsed_field.name])
    lines += ["};", ""]

    lines += [
        f"constexpr TypeInfo type_{index}_ = TypeInfo{{",
        f'    .name = "{_string(parsed.name)}",',
        f"    .id = TypeId{{{identity.types[parsed.name]}}},",
        f"    .size = static_cast<u32>(sizeof({alias})),",
        f"    .alignment = static_cast<u32>(alignof({alias})),",
        f"    .trivially_relocatable = std::is_trivially_copyable_v<{alias}> &&",
        f"                             std::is_trivially_destructible_v<{alias}>,",
        f"    .construct = &construct_{index}_,",
        f"    .destruct = &destruct_{index}_,",
        f"    .copy_assign = &copy_assign_{index}_,",
        f"    .fields = fields_{index}_,",
        f"    .field_count = {len(parsed.fields)},",
        "    .methods = nullptr,",
        "    .method_count = 0,",
        f'    .header = "{_string(parsed.header)}",',
        f'    .module = "{_string(parsed.module)}",',
        "};",
        "",
    ]
    return lines


def _render_field_payloads(type_index: int, position: int, attributes: Attributes) -> list[str]:
    lines: list[str] = []
    if attributes.enumerators:
        lines.append(f"constexpr Enumerator enumerators_{type_index}_{position}_[] = {{")
        for name, value in attributes.enumerators:
            lines.append(f'    Enumerator{{"{_string(name)}", {value}}},')
        lines.append("};")
    for order, custom in enumerate(attributes.custom):
        lines += _render_custom(type_index, position, order, custom)
    if attributes.custom:
        lines.append(f"constexpr CustomAttribute customs_{type_index}_{position}_[] = {{")
        for order, custom in enumerate(attributes.custom):
            lines.append(
                f'    CustomAttribute{{"{_string(custom.schema.name)}", '
                f"&custom_{type_index}_{position}_{order}_value,"
            )
            lines.append(
                f"                    static_cast<u32>(sizeof({custom.schema.qualified_struct}))}},"
            )
        lines.append("};")
    if lines:
        lines.append("")
    return lines


def _render_custom(type_index: int, position: int, order: int, custom: CustomValue) -> list[str]:
    name = f"custom_{type_index}_{position}_{order}_"
    # In the schema's declaration order, which is the order the struct's members are emitted in.
    # Never the dictionary's: the incremental cache round-trips it through sorted JSON, so a
    # dictionary order here would silently reorder an initialiser between a cold run and a warm one.
    values = ", ".join(
        _literal(custom.values[parameter.name]) for parameter in custom.schema.parameters
    )
    return [
        f"constexpr {custom.schema.qualified_struct} {name}value{{{values}}};",
    ]


def _render_field(type_index: int, position: int, alias: str, parsed_field,
                  identifier: int) -> list[str]:
    attributes = parsed_field.attributes
    lines = [
        "    FieldInfo{",
        f'        .name = "{_string(parsed_field.name)}",',
        f"        .id = FieldId{{{identifier}}},",
        f"        .kind = FieldKind::{parsed_field.kind},",
        "        .type = TypeId{},",
        f"        .offset = static_cast<u32>(offsetof({alias}, {parsed_field.name})),",
        f"        .size = static_cast<u32>(sizeof({alias}::{parsed_field.name})),",
        "        .attributes = FieldAttributes{",
        f"            .declared = {_declared(attributes)},",
    ]
    if attributes.range is not None:
        minimum, maximum, step = attributes.range
        lines.append(
            f"            .range = RangeAttribute{{{_double(minimum)}, {_double(maximum)}, "
            f"{_double(step)}}},"
        )
    if attributes.enumerators:
        array = f"enumerators_{type_index}_{position}_"
        lines.append(
            f"            .enumeration = EnumAttribute{{{array}, {len(attributes.enumerators)}}},"
        )
    if attributes.category is not None:
        lines.append(f'            .category = TextAttribute{{"{_string(attributes.category)}"}},')
    if attributes.tooltip is not None:
        lines.append(f'            .tooltip = TextAttribute{{"{_string(attributes.tooltip)}"}},')
    if attributes.replicated is not None:
        encoder, parameters, condition = attributes.replicated
        lines.append(
            f'            .replicated = ReplicatedAttribute{{"{_string(encoder)}", '
            f'"{_string(parameters)}", "{_string(condition)}"}},'
        )
    if attributes.asset_ref is not None:
        lines.append(
            f'            .asset_ref = AssetRefAttribute{{"{_string(attributes.asset_ref)}"}},'
        )
    lines.append(f"            .unit = UnitKind::{attributes.unit},")
    lines.append(f"            .persistence = PersistenceKind::{attributes.persistence},")
    if attributes.custom:
        lines += _custom_array_lines(type_index, position, attributes)
    lines += ["        },", "    },"]
    return lines


def _custom_array_lines(type_index: int, position: int, attributes: Attributes) -> list[str]:
    return [
        f"            .custom = customs_{type_index}_{position}_,",
        f"            .custom_count = {len(attributes.custom)},",
    ]


def render_aggregate(headers: list[ParsedHeader]) -> Output:
    """The one translation unit that registers everything, in a fixed order."""
    ordered = sorted(headers, key=lambda parsed: parsed.include_path)
    lines = [
        BANNER.format(source="every annotated header this module named"),
        "",
        "#include <cy/core/reflect/reflect.h>",
        "",
    ]
    for parsed in ordered:
        lines.append(f"#include <{outputs_for(parsed.include_path)[0]}>")
    lines += [
        "",
        "namespace cy::reflect {",
        "",
        "Status register_generated_types(TypeRegistry& registry) {",
    ]
    for parsed in ordered:
        slug = slug_of(parsed.include_path)
        lines += [
            f"    if (auto added = register_{slug}(registry); !added) {{",
            "        return added;",
            "    }",
        ]
    lines += [
        "    return ok();",
        "}",
        "",
        "Status register_generated_types() {",
        "    return register_generated_types(default_registry());",
        "}",
        "",
        "}  // namespace cy::reflect",
    ]
    return Output("cy_reflect_generated.cpp", _document(lines))


# --- Literals -----------------------------------------------------------------------------------


def _declared(attributes: Attributes) -> str:
    if not attributes.declared:
        return "AttributeKind::None"
    joined = " | ".join(f"AttributeKind::{name}" for name in sorted(attributes.declared))
    if len(joined) <= 60:
        return joined
    indent = "\n                        | "
    return indent.join(f"AttributeKind::{name}" for name in sorted(attributes.declared)).lstrip()


def _string(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def _double(value: float) -> str:
    """A double literal that reads back as the same double. repr() is shortest round-trip."""
    text = repr(float(value))
    return text if any(character in text for character in ".eE") else f"{text}.0"


def _literal(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return f'"{_string(value)}"'
    if isinstance(value, float):
        return _double(value)
    return str(value)
