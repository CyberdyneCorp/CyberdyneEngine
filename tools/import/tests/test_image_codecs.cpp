/// What the generator wrote, which is what a correct decoder must return.
void expected_texel(u32 x, u32 y, u8 out[4]) {
    out[0] = static_cast<u8>(x * 17U);
    out[1] = static_cast<u8>(y * 17U);
    out[2] = static_cast<u8>((x * y) % 256U);
    out[3] = ((x + y) % 5U) != 0 ? 255U : 128U;
}

// --- Reference decoders, written from the format tables
// ---------------------------------------------

u32 bc7_bits(const u8 block[16], u32 start, u32 count) {
    u32 value = 0;
    for (u32 index = 0; index < count; ++index) {
        const u32 bit = start + index;
        value |= static_cast<u32>((block[bit / 8U] >> (bit % 8U)) & 1U) << index;
    }
    return value;
}

/// Decode a BC7 mode 6 block. Refuses any other mode by returning false, which is itself an
/// assertion: an encoder that silently emitted a different mode would fail here rather than produce
/// a picture nobody checked.
bool decode_bc7_mode6(const u8 block[16], u8 out[64]) {
    static const u8 kWeights[16] = {0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64};
    if (bc7_bits(block, 0, 7) != (1U << 6U)) {
        return false;
    }
    u32 field[2][4];
    u32 cursor = 7;
    for (u32 channel = 0; channel < 4; ++channel) {
        field[0][channel] = bc7_bits(block, cursor, 7);
        cursor += 7;
        field[1][channel] = bc7_bits(block, cursor, 7);
        cursor += 7;
    }
    const u32 p0 = bc7_bits(block, cursor++, 1);
    const u32 p1 = bc7_bits(block, cursor++, 1);
    u32 endpoint[2][4];
    for (u32 channel = 0; channel < 4; ++channel) {
        endpoint[0][channel] = (field[0][channel] << 1U) | p0;
        endpoint[1][channel] = (field[1][channel] << 1U) | p1;
    }
    for (u32 texel = 0; texel < 16; ++texel) {
        const u32 count = texel == 0 ? 3U : 4U;
        const u32 index = bc7_bits(block, cursor, count);
        cursor += count;
        for (u32 channel = 0; channel < 4; ++channel) {
            const u32 weight = kWeights[index];
            out[(texel * 4U) + channel] = static_cast<u8>(
                ((endpoint[0][channel] * (64U - weight)) + (endpoint[1][channel] * weight) + 32U) >>
                6U);
        }
    }
    return true;
}

void decode_bc4(const u8 block[8], u8 out[16]) {
    const u32 red0 = block[0];
    const u32 red1 = block[1];
    u32 palette[8];
    palette[0] = red0;
    palette[1] = red1;
    if (red0 > red1) {
        for (u32 step = 2; step < 8; ++step) {
            palette[step] = (((8U - step) * red0) + ((step - 1U) * red1)) / 7U;
        }
    } else {
        for (u32 step = 2; step < 6; ++step) {
            palette[step] = (((6U - step) * red0) + ((step - 1U) * red1)) / 5U;
        }
        palette[6] = 0;
        palette[7] = 255;
    }
    u64 packed = 0;
    for (u32 index = 0; index < 6; ++index) {
        packed |= static_cast<u64>(block[2 + index]) << (index * 8U);
    }
    for (u32 texel = 0; texel < 16; ++texel) {
        out[texel] = static_cast<u8>(palette[(packed >> (texel * 3U)) & 7U]);
    }
}

cy::Span<const u8> span_of(const u8* data, usize size) {
    return cy::Span<const u8>(data, size);
}

