/// The bundle's own format version. A cache entry written by another version is a miss, which the
/// derivation key already guarantees — the pipeline's version is part of it — so this is a
/// belt-and-braces check that costs four bytes.
constexpr u32 kBundleVersion = 1;

/// The version of the PIPELINE, distinct from any importer's.
///
/// It is a contribution to every derivation key this pipeline produces, so that a change to how a
/// result is bundled, published or named re-cooks the project rather than serving entries laid out
/// the old way. An importer's own version covers its own output; this covers everything around it.
constexpr u32 kPipelineVersion = 1;

void put_u32(Array<u8>& out, u32 value) noexcept {
    for (u32 index = 0; index < 4; ++index) {
        (void)out.push_back(static_cast<u8>((value >> (index * 8U)) & 0xFFU));
    }
}

[[nodiscard]] u32 get_u32(const u8* data) noexcept {
    u32 value = 0;
    for (u32 index = 0; index < 4; ++index) {
        value |= static_cast<u32>(data[index]) << (index * 8U);
    }
    return value;
}

/// `<root>/<relative>` in a fixed buffer, refusing anything that does not fit.
[[nodiscard]] Status join_native(std::string_view root, std::string_view relative, char* out,
                                 usize capacity) noexcept {
    const usize needed = root.size() + 1 + relative.size();
    if (needed + 1 > capacity) {
        return fail(ErrorCode::OutOfRange, "a native path longer than this build's buffer");
    }
    usize written = 0;
    if (!root.empty()) {
        std::memcpy(out, root.data(), root.size());
        written = root.size();
        if (out[written - 1] != '/') {
            out[written++] = '/';
        }
    }
    std::memcpy(out + written, relative.data(), relative.size());
    written += relative.size();
    out[written] = '\0';
    return ok();
}

/// One sub-asset in a cached bundle. The public spellings are `encode_import_bundle` and
/// `decode_import_bundle`, at the bottom of this file; these are what they call.
[[nodiscard]] Status encode_bundle(const ImportResult& result, Array<u8>& out) noexcept {
    put_u32(out, kBundleVersion);
    put_u32(out, static_cast<u32>(result.assets().size()));
    for (const SubAsset& produced : result.assets()) {
        const std::string_view name = produced.view();
        put_u32(out, static_cast<u32>(name.size()));
        if (Status appended =
                out.append(Span<const u8>(reinterpret_cast<const u8*>(name.data()), name.size()));
            !appended) {
            return appended;
        }
        put_u32(out, static_cast<u32>(produced.kind));
        put_u32(out, produced.primary ? 1U : 0U);
        put_u32(out, static_cast<u32>(produced.payload.size()));
        if (Status appended =
                out.append(Span<const u8>(produced.payload.data(), produced.payload.size()));
            !appended) {
            return appended;
        }
    }
    // Diagnostics are NOT bundled, and that is deliberate. A warning is about the source and is
    // regenerated by re-running the importer; storing it would mean a cache hit reported warnings
    // for a state of the file that may no longer exist, which is worse than reporting none.
    return ok();
}

[[nodiscard]] Status decode_bundle(Span<const u8> payload, ImportResult& out) noexcept {
    if (payload.size() < 8 || get_u32(payload.data()) != kBundleVersion) {
        return fail(ErrorCode::InvalidArgument, "a cached import bundle this build does not read");
    }
    const usize count = get_u32(payload.data() + 4);
    usize cursor = 8;
    for (usize index = 0; index < count; ++index) {
        if (cursor + 4 > payload.size()) {
            return fail(ErrorCode::InvalidArgument, "a bundle that ends inside a sub-asset");
        }
        const usize name_length = get_u32(payload.data() + cursor);
        cursor += 4;
        if (cursor + name_length + 12 > payload.size()) {
            return fail(ErrorCode::InvalidArgument, "a bundle that ends inside a sub-asset");
        }
        const std::string_view name(reinterpret_cast<const char*>(payload.data() + cursor),
                                    name_length);
        cursor += name_length;
        const auto kind = static_cast<assets::AssetKind>(get_u32(payload.data() + cursor));
        const bool primary = get_u32(payload.data() + cursor + 4) != 0;
        const usize payload_length = get_u32(payload.data() + cursor + 8);
        cursor += 12;
        if (cursor + payload_length > payload.size()) {
            return fail(ErrorCode::InvalidArgument, "a bundle that ends inside a payload");
        }
        Array<u8> bytes;
        if (Status appended = bytes.append(Span<const u8>(payload.data() + cursor, payload_length));
            !appended) {
            return appended;
        }
        cursor += payload_length;
        if (Status added = out.add(kind, name, std::move(bytes), primary); !added) {
            return added;
        }
    }
    if (cursor != payload.size()) {
        return fail(ErrorCode::InvalidArgument, "a bundle with trailing bytes");
    }
    return ok();
}

[[nodiscard]] u64 now_micros() noexcept {
    const auto now = std::chrono::steady_clock::now().time_since_epoch();
    return static_cast<u64>(std::chrono::duration_cast<std::chrono::microseconds>(now).count());
}

void copy_into(char* out, usize capacity, std::string_view text) noexcept {
    const usize length = text.size() < capacity - 1 ? text.size() : capacity - 1;
    if (length != 0) {
        std::memcpy(out, text.data(), length);
    }
    out[length] = '\0';
}

