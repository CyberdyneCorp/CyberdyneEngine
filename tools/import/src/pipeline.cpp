FileImportResolver::FileImportResolver(std::string_view project_root,
                                       const assets::VirtualPath& source,
                                       ImportResult& result) noexcept
    : project_root_(project_root), result_(&result) {
    const std::string_view parent = source.parent();
    // A source at the project root has no parent, and normalising an empty string is an error, so
    // the empty path is left as it is — which is exactly "the root".
    if (!parent.empty()) {
        Expected<assets::VirtualPath, Error> directory = assets::VirtualPath::normalise(parent);
        if (directory) {
            directory_ = directory.value();
        }
    }
}

Expected<Span<const u8>, Error> FileImportResolver::read(std::string_view path) noexcept {
    // Relative to the source's own directory first, then the project root. That is the order every
    // content pipeline uses and the order an artist expects: a `.bin` beside a `.gltf` wins over a
    // file of the same name at the top of the project.
    assets::VirtualPath resolved;
    if (!directory_.empty()) {
        Expected<assets::VirtualPath, Error> beside = directory_.join(path);
        if (beside) {
            resolved = beside.value();
        }
    }
    if (resolved.empty()) {
        Expected<assets::VirtualPath, Error> absolute = assets::VirtualPath::normalise(path);
        if (!absolute) {
            return make_unexpected(absolute.error());
        }
        resolved = absolute.value();
    }

    for (const Buffer& buffer : buffers_) {
        if (buffer.path == resolved) {
            return Span<const u8>(buffer.bytes.data(), buffer.bytes.size());
        }
    }

    char native[assets::kMaxPathLength * 2] = {};
    if (Status joined = join_native(project_root_, resolved.view(), native, sizeof(native));
        !joined) {
        return make_unexpected(joined.error());
    }

    Buffer buffer;
    buffer.path = resolved;
    if (Status read = assets::fs::read_whole(native, buffer.bytes); !read) {
        // Fall back to the project root when the file was not beside the source. Two lookups rather
        // than one guess, because a missing file and a file in the other place are different
        // answers and only one of them is a diagnostic.
        Expected<assets::VirtualPath, Error> absolute = assets::VirtualPath::normalise(path);
        if (!absolute) {
            return make_unexpected(read.error());
        }
        char fallback[assets::kMaxPathLength * 2] = {};
        if (Status joined =
                join_native(project_root_, absolute.value().view(), fallback, sizeof(fallback));
            !joined) {
            return make_unexpected(joined.error());
        }
        if (Status second = assets::fs::read_whole(fallback, buffer.bytes); !second) {
            return make_unexpected(second.error());
        }
        buffer.path = absolute.value();
    }

    const assets::ContentHash digest =
        assets::content_hash(buffer.bytes.data(), buffer.bytes.size());
    if (Status recorded = result_->add_dependency(buffer.path.view(), digest); !recorded) {
        return make_unexpected(recorded.error());
    }
    if (Status pushed = buffers_.push_back(std::move(buffer)); !pushed) {
        return make_unexpected(pushed.error());
    }
    const Buffer& stored = buffers_[buffers_.size() - 1];
    return Span<const u8>(stored.bytes.data(), stored.bytes.size());
}

Status FileImportResolver::observe(std::string_view name,
                                   const assets::ContentHash& digest) noexcept {
    return result_->add_dependency(name, digest);
}

