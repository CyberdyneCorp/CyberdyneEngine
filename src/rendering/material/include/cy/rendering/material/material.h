#pragma once
// The material model, its parameter storage, and the GPU material table. Task 4.2.4.
//
// `rendering-materials-and-shading` — "Material model": a material is "an authored definition, a
// compiled **material program** produced by the material compiler, a parameter block, and a
// resource block", parameters are **static** (part of the program's structure) or **runtime** (data
// that changes without recompilation), and instances "reference a program and override a subset of
// runtime parameters", creatable at runtime with no compilation.
//
// ================================================================================================
// WHAT M3 BUILDS AND WHAT M7 BUILDS, BECAUSE THE SPLIT IS THE INTERESTING PART
// ================================================================================================
//
// design.md §5: "M3 integrates Slang → SPIR-V and builds the caching, permutation and
// reflection-driven binding around it. It does NOT build the material compiler — that is M7's."
//
// So there is no closure graph here, no lowering, and no code generation. What is here is the shape
// a compiled program HAS — a parameter layout, a shading model, a blend mode, a permutation key —
// and the storage its parameters live in. A material authored as data at M3 fills that shape
// directly; a material compiled from a closure graph at M7 fills the same shape, and nothing
// downstream changes. The seam is that `MaterialProgram` is a description rather than a compiler
// output type.
//
// ================================================================================================
// PARAMETER STORAGE: WHY A TABLE AND NOT A DESCRIPTOR SET PER MATERIAL
// ================================================================================================
//
// "Material parameters and resource references SHALL live in the GPU material table, addressed by a
// material identifier carried in GPU scene instance data", and the scenario is "WHEN a
// GPU-generated draw shades a pixel THEN it SHALL index the material table using the instance's
// material identifier, with no per-object descriptor binding."
//
// That requirement is what makes GPU-driven rendering possible at all: a draw generated by a
// compute shader has no CPU in the loop to bind anything. So a material's parameters are BYTES AT
// AN INDEX, the index is `GpuInstance::material`, and the table is one buffer.
//
// Three consequences worth stating because each is a decision:
//
//   * Every material's parameter block is the same size (`kMaterialBlockBytes`), so the index is a
//     multiplication rather than an offset table the shader would have to read first.
//   * A parameter is addressed by a `ParameterId` — a hash of its name, computed at compile time —
//     and resolved to an offset once, when the program is described. "Parameter names SHALL resolve
//     to compile-time identifiers; per-frame string lookup SHALL NOT be required."
//   * Changing a parameter marks ONE material's range dirty, and `MaterialTable::dirty_range()`
//     merges them into one transfer. "Parameter updates SHALL be batched: changed materials SHALL
//     be collected during Prepare and uploaded in one transfer."
//
// Textures are indices into bindless descriptor arrays, stored in the block like any other
// parameter, "with per-material descriptor sets used only on the compatibility path".

